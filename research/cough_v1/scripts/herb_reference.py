def _parse_norm(text):
    out = {}
    for line in text.strip().splitlines():
        raw, rest = line.split('>')
        std, note = (rest.split('|') + [''])[:2]
        out[raw.strip()] = (std.strip(), note.strip())
    return out


def _parse_props(text):
    out = {}
    for line in text.strip().splitlines():
        f = line.split('|')
        name, qi, wei, gui, tox, cat, sub, src, note = (f + [''] * 9)[:9]
        out[name] = dict(qi=qi, wei=[w for w in wei.split(',') if w], gui=[g for g in gui.split(',') if g],
                         tox=tox, cat=cat, sub=sub, src=src, note=note)
    return out


